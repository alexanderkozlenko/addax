using System.Text;
using Addax.Formats.Tabular.Analyzers.CSharp.Primitives;

namespace Addax.Formats.Tabular.Analyzers.CSharp
{
    internal partial class TabularHandlerEmitter
    {
        private static void BuildHandlerSource(SourceTextWriter writer, string typeName, in TabularRecordMapping recordMapping)
        {
            var recordMappingSupportsHeader = MappingSupportsHeader(recordMapping);
            var recordMappingSupportsReading = MappingSupportsReading(recordMapping);
            var recordMappingSupportsWriting = MappingSupportsWriting(recordMapping);
            var recordMappingHasConverters = MappingHasConverters(recordMapping);
            var fieldOrders = GetFieldOrders(recordMapping);

            writer.WriteLine("// <auto-generated />");
            writer.WriteLine();
            writer.WriteLine("#nullable disable");

            if (!recordMapping.ExperimentalDiagnosticIds.IsEmpty)
            {
                var experimentalDiagnosticIds = new StringBuilder();

                foreach (var experimentalDiagnosticId in recordMapping.ExperimentalDiagnosticIds)
                {
                    if (experimentalDiagnosticIds.Length != 0)
                    {
                        experimentalDiagnosticIds.Append(", ");
                    }

                    experimentalDiagnosticIds.Append(experimentalDiagnosticId);
                }

                writer.WriteLine();
                writer.WriteLine($"#pragma warning disable {experimentalDiagnosticIds}");
            }

            writer.WriteLine();
            writer.WriteLine("namespace Addax.Formats.Tabular.Handlers;");
            writer.WriteLine();
            writer.WriteLine($"[global::System.CodeDom.Compiler.GeneratedCode(\"{s_assemblyInfo.Name}\", \"{s_assemblyInfo.Version}\")]");
            writer.WriteLine($"file sealed class {typeName} : global::Addax.Formats.Tabular.TabularHandler<{recordMapping.TypeName}>");
            writer.WriteLine("{");
            writer.Indent++;

            if (recordMappingSupportsHeader)
            {
                BuildHeaderField(writer, recordMapping, fieldOrders);
            }

            if (recordMappingHasConverters)
            {
                if (recordMappingSupportsHeader)
                {
                    writer.WriteLine();
                }

                BuildConverterFields(writer, recordMapping, fieldOrders);
            }

            if (recordMappingSupportsHeader || recordMappingHasConverters)
            {
                writer.WriteLine();
            }

            BuildRegisterMethod(writer, typeName, recordMapping);

            if (recordMappingSupportsReading)
            {
                writer.WriteLine();

                BuildReadMethod(writer, recordMapping, fieldOrders, false);

                writer.WriteLine();

                BuildReadMethod(writer, recordMapping, fieldOrders, true);
            }

            if (recordMappingSupportsWriting)
            {
                writer.WriteLine();

                BuildWriteMethod(writer, recordMapping, fieldOrders, false);

                writer.WriteLine();

                BuildWriteMethod(writer, recordMapping, fieldOrders, true);
            }

            if (recordMappingSupportsHeader)
            {
                writer.WriteLine();

                BuildHeaderProperty(writer);
            }

            writer.Indent--;
            writer.WriteLine("}");
        }

        private static void BuildHeaderField(SourceTextWriter writer, in TabularRecordMapping recordMapping, int[] fieldOrders)
        {
            writer.WriteLine("private static readonly global::System.String[] s_header =");
            writer.WriteLine("[");
            writer.Indent++;

            for (var i = 0; i < fieldOrders.Length; i++)
            {
                var fieldMapping = recordMapping.FieldMappings[i];

                if (!fieldMapping.SupportsReading)
                {
                    continue;
                }

                if (fieldMapping.FieldNameLiteral != null)
                {
                    writer.WriteLine($"{fieldMapping.FieldNameLiteral},");
                }
                else
                {
                    writer.WriteLine("\"\",");
                }
            }

            writer.Indent--;
            writer.WriteLine("];");
        }

        private static void BuildConverterFields(SourceTextWriter writer, in TabularRecordMapping recordMapping, int[] fieldOrders)
        {
            for (var i = 0; i < fieldOrders.Length; i++)
            {
                var fieldOrder = fieldOrders[i];
                var fieldMapping = recordMapping.FieldMappings[i];

                if (fieldMapping.ConverterTypeName != null)
                {
                    writer.WriteLine($"private readonly {fieldMapping.ConverterTypeName} _c{fieldOrder} = new();");
                }
            }
        }

        private static void BuildRegisterMethod(SourceTextWriter writer, string typeName, in TabularRecordMapping recordMapping)
        {
            writer.WriteLine("[global::System.Runtime.CompilerServices.ModuleInitializer]");
            writer.WriteLine("public static void Register()");
            writer.WriteLine("{");
            writer.Indent++;
            writer.WriteLine($"global::Addax.Formats.Tabular.TabularRegistry.Handlers[typeof({recordMapping.TypeName})] = new {typeName}();");
            writer.Indent--;
            writer.WriteLine("}");
        }

        private static void BuildReadMethod(SourceTextWriter writer, in TabularRecordMapping recordMapping, int[] fieldOrders, bool isAsync)
        {
            var trySkipFieldCall = isAsync ? "await reader.TrySkipFieldAsync(cancellationToken).ConfigureAwait(false)" : "reader.TrySkipField()";
            var tryReadFieldCall = isAsync ? "await reader.TryReadFieldAsync(cancellationToken).ConfigureAwait(false)" : "reader.TryReadField()";

            if (isAsync)
            {
                writer.WriteLine($"public override async global::System.Threading.Tasks.ValueTask<global::Addax.Formats.Tabular.TabularRecord<{recordMapping.TypeName}>> ReadAsync(global::Addax.Formats.Tabular.TabularReader reader, global::System.Threading.CancellationToken cancellationToken)");
            }
            else
            {
                writer.WriteLine($"public override global::Addax.Formats.Tabular.TabularRecord<{recordMapping.TypeName}> Read(global::Addax.Formats.Tabular.TabularReader reader)");
            }

            writer.WriteLine("{");
            writer.Indent++;

            var fieldTypeCheckEmitted = false;
            var currentFieldOrder = -1;

            for (var i = 0; i < fieldOrders.Length; i++)
            {
                var fieldOrder = fieldOrders[i];
                var fieldMapping = recordMapping.FieldMappings[i];

                if (!fieldMapping.SupportsWriting)
                {
                    continue;
                }

                var fieldsToSkip = fieldOrder - (currentFieldOrder + 1);

                if (fieldsToSkip > 0)
                {
                    if (fieldTypeCheckEmitted)
                    {
                        writer.WriteLine($"if (!{trySkipFieldCall})");
                    }
                    else
                    {
                        writer.WriteLine($"if (!{trySkipFieldCall} || (reader.CurrentFieldType != global::Addax.Formats.Tabular.TabularFieldType.Value))");
                        fieldTypeCheckEmitted = true;
                    }

                    writer.WriteLine("{");
                    writer.Indent++;
                    writer.WriteLine("return default;");
                    writer.Indent--;
                    writer.WriteLine("}");
                    writer.WriteLine();

                    if (fieldsToSkip > 1)
                    {
                        writer.WriteLine($"for (var i = 1; i < {fieldsToSkip}; i++)");
                        writer.WriteLine("{");
                        writer.Indent++;
                        writer.WriteLine($"if (!{trySkipFieldCall})");
                        writer.WriteLine("{");
                        writer.Indent++;
                        writer.WriteLine("return default;");
                        writer.Indent--;
                        writer.WriteLine("}");
                        writer.Indent--;
                        writer.WriteLine("}");
                        writer.WriteLine();
                    }
                }

                if (fieldTypeCheckEmitted)
                {
                    writer.WriteLine($"if (!{tryReadFieldCall})");
                }
                else
                {
                    writer.WriteLine($"if (!{tryReadFieldCall} || (reader.CurrentFieldType != global::Addax.Formats.Tabular.TabularFieldType.Value))");
                    fieldTypeCheckEmitted = true;
                }

                writer.WriteLine("{");
                writer.Indent++;
                writer.WriteLine("return default;");
                writer.Indent--;
                writer.WriteLine("}");
                writer.WriteLine();

                var defaultValue = !fieldMapping.IsNullableT ? "default" : $"default({fieldMapping.ValueTypeName}?)";

                if (fieldMapping.ConverterTypeName == null)
                {
                    var valueTypeCode = GetValueTypeCode(fieldMapping.ValueTypeName);

                    writer.WriteLine($"var v{fieldOrder} = reader.TryGet{valueTypeCode}(out var f{fieldOrder}) ? f{fieldOrder} : {defaultValue};");
                }
                else
                {
                    writer.WriteLine($"var v{fieldOrder} = reader.TryGet(_c{fieldOrder}, out var f{fieldOrder}) ? f{fieldOrder} : {defaultValue};");
                }

                writer.WriteLine();
                currentFieldOrder = fieldOrder;
            }

            BuildRecordConstruction(writer, recordMapping, fieldOrders);

            writer.WriteLine();
            writer.WriteLine("return new(r);");
            writer.Indent--;
            writer.WriteLine("}");
        }

        private static void BuildWriteMethod(SourceTextWriter writer, in TabularRecordMapping recordMapping, int[] fieldOrders, bool isAsync)
        {
            if (isAsync)
            {
                writer.WriteLine($"public override async global::System.Threading.Tasks.ValueTask WriteAsync(global::Addax.Formats.Tabular.TabularWriter writer, {recordMapping.TypeName} record, global::System.Threading.CancellationToken cancellationToken)");
            }
            else
            {
                writer.WriteLine($"public override void Write(global::Addax.Formats.Tabular.TabularWriter writer, {recordMapping.TypeName} record)");
            }

            writer.WriteLine("{");
            writer.Indent++;

            for (var i = 0; i < fieldOrders.Length; i++)
            {
                var fieldOrder = fieldOrders[i];
                var fieldMapping = recordMapping.FieldMappings[i];

                if (!fieldMapping.SupportsReading)
                {
                    continue;
                }

                if (fieldMapping.ConverterTypeName == null)
                {
                    var valueTypeCode = GetValueTypeCode(fieldMapping.ValueTypeName);

                    if (fieldMapping.IsNullableT)
                    {
                        writer.WriteLine($"if (record.{fieldMapping.MemberIdentifier} is {{ }} v{fieldOrder})");
                        writer.WriteLine("{");
                        writer.Indent++;
                        writer.WriteLine(GetWriterCall($"Write{valueTypeCode}", $"v{fieldOrder}", isAsync));
                        writer.Indent--;
                        writer.WriteLine("}");
                        writer.WriteLine("else");
                        writer.WriteLine("{");
                        writer.Indent++;
                        writer.WriteLine(GetWriterCall("WriteEmpty", "", isAsync));
                        writer.Indent--;
                        writer.WriteLine("}");
                    }
                    else
                    {
                        writer.WriteLine(GetWriterCall($"Write{valueTypeCode}", $"record.{fieldMapping.MemberIdentifier}", isAsync));
                    }
                }
                else
                {
                    if (fieldMapping.IsNullableT)
                    {
                        writer.WriteLine($"if (record.{fieldMapping.MemberIdentifier} is {{ }} v{fieldOrder})");
                        writer.WriteLine("{");
                        writer.Indent++;
                        writer.WriteLine(GetWriterCall("Write", $"v{fieldOrder}, _c{fieldOrder}", isAsync));
                        writer.Indent--;
                        writer.WriteLine("}");
                        writer.WriteLine("else");
                        writer.WriteLine("{");
                        writer.Indent++;
                        writer.WriteLine(GetWriterCall("WriteEmpty", "", isAsync));
                        writer.Indent--;
                        writer.WriteLine("}");
                    }
                    else
                    {
                        writer.WriteLine(GetWriterCall("Write", $"record.{fieldMapping.MemberIdentifier}, _c{fieldOrder}", isAsync));
                    }
                }

                if (i < recordMapping.FieldMappings.Count - 1)
                {
                    writer.WriteLine();
                }
            }

            writer.Indent--;
            writer.WriteLine("}");
        }

        private static void BuildHeaderProperty(SourceTextWriter writer)
        {
            writer.WriteLine("public override global::System.Collections.Generic.IEnumerable<global::System.String> Header");
            writer.WriteLine("{");
            writer.Indent++;
            writer.WriteLine("get");
            writer.WriteLine("{");
            writer.Indent++;
            writer.WriteLine("return s_header;");
            writer.Indent--;
            writer.WriteLine("}");
            writer.Indent--;
            writer.WriteLine("}");
        }

        private static void BuildRecordConstruction(SourceTextWriter writer, in TabularRecordMapping recordMapping, int[] fieldOrders)
        {
            if (!recordMapping.ConstructorArguments.IsEmpty)
            {
                var constructorArguments = new StringBuilder();

                foreach (var fieldOrder in recordMapping.ConstructorArguments)
                {
                    if (constructorArguments.Length != 0)
                    {
                        constructorArguments.Append(", ");
                    }

                    constructorArguments.Append($"v{fieldOrder}");
                }

                writer.WriteLine($"var r = new {recordMapping.TypeName}({constructorArguments});");

                return;
            }

            writer.WriteLine($"var r = new {recordMapping.TypeName}");
            writer.WriteLine("{");
            writer.Indent++;

            for (var i = 0; i < fieldOrders.Length; i++)
            {
                var fieldOrder = fieldOrders[i];
                var fieldMapping = recordMapping.FieldMappings[i];

                if (fieldMapping.SupportsWriting)
                {
                    writer.WriteLine($"{fieldMapping.MemberIdentifier} = v{fieldOrder},");
                }
            }

            writer.Indent--;
            writer.WriteLine("};");
        }

        private static string GetWriterCall(string methodName, string arguments, bool isAsync)
        {
            if (isAsync)
            {
                var asyncArguments = (arguments.Length != 0) ? $"{arguments}, cancellationToken" : "cancellationToken";

                return $"await writer.{methodName}Async({asyncArguments}).ConfigureAwait(false);";
            }

            return $"writer.{methodName}({arguments});";
        }
    }
