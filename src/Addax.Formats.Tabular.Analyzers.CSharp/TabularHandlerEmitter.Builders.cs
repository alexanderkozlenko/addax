using System;
using System.Collections.Generic;
using System.Linq;
using Addax.Formats.Tabular.Analyzers.CSharp.Primitives;

namespace Addax.Formats.Tabular.Analyzers.CSharp
{
    internal static partial class TabularHandlerEmitter
    {
        private static void BuildHandlerSource(SourceTextWriter writer, string typeName, in TabularRecordMapping recordMapping)
        {
            var recordMappingSupportsHeader = MappingSupportsHeader(recordMapping);
            var recordMappingSupportsReading = (recordMapping.RecordAccess & TabularRecordAccess.Read) != 0;
            var recordMappingSupportsWriting = (recordMapping.RecordAccess & TabularRecordAccess.Write) != 0;
            var recordMappingHasConverters = MappingHasConverters(recordMapping);

            writer.WriteLine("// <auto-generated />");
            writer.WriteLine();
            writer.WriteLine("#nullable disable");

            if (!recordMapping.DiagnosticIdentifiers.IsEmpty)
            {
                writer.WriteLine();

                foreach (var diagnosticIdentifier in recordMapping.DiagnosticIdentifiers)
                {
                    writer.WriteLine($"#pragma warning disable {diagnosticIdentifier}");
                }
            }

            writer.WriteLine();
            writer.WriteLine("namespace Addax.Formats.Tabular.Handlers;");
            writer.WriteLine();
            writer.WriteLine($"[global::System.CodeDom.Compiler.GeneratedCode(\"{s_assemblyInfo.Name}\", \"{s_assemblyInfo.Version}\")]");
            writer.WriteLine($"file sealed class {typeName} : global::Addax.Formats.Tabular.TabularHandler<{recordMapping.TypeName}>");
            writer.WriteLine("{");
            writer.Indent++;

            if (recordMappingSupportsHeader)
            {
                BuildHeaderField(writer, recordMapping);

                writer.WriteLine();
            }

            if (recordMappingHasConverters)
            {
                BuildConverterFields(writer, recordMapping);

                writer.WriteLine();
            }

            BuildRegisterMethod(writer, typeName, recordMapping);

            if (recordMappingSupportsReading)
            {
                writer.WriteLine();

                BuildReadMethod(writer, recordMapping, false);

                writer.WriteLine();

                BuildReadMethod(writer, recordMapping, true);
            }

            if (recordMappingSupportsWriting)
            {
                writer.WriteLine();

                BuildWriteMethod(writer, recordMapping, false);

                writer.WriteLine();

                BuildWriteMethod(writer, recordMapping, true);
            }

            if (recordMappingSupportsReading)
            {
                writer.WriteLine();

                BuildThrowFieldConversionMethod(writer);

                writer.WriteLine();

                BuildThrowMissingFieldMethod(writer);
            }

            if (recordMappingSupportsHeader)
            {
                writer.WriteLine();

                BuildHeaderProperty(writer);
            }

            writer.Indent--;
            writer.WriteLine("}");
        }

        private static void BuildHeaderField(SourceTextWriter writer, in TabularRecordMapping recordMapping)
        {
            writer.WriteLine("private static readonly global::System.String[] s_header =");
            writer.WriteLine("[");
            writer.Indent++;

            var fieldOrder = 0;

            foreach (var fieldMapping in recordMapping.FieldMappings)
            {
                if (fieldOrder < fieldMapping.FieldOrder)
                {
                    writer.WriteLine($".. global::System.Linq.Enumerable.Repeat(\"\", {fieldMapping.FieldOrder - fieldOrder}),");
                }

                if (fieldMapping.FieldNameLiteral != null)
                {
                    writer.WriteLine($"{fieldMapping.FieldNameLiteral},");
                }
                else
                {
                    writer.WriteLine("\"\",");
                }

                fieldOrder = fieldMapping.FieldOrder + 1;
            }

            writer.Indent--;
            writer.WriteLine("];");
        }

        private static void BuildConverterFields(SourceTextWriter writer, in TabularRecordMapping recordMapping)
        {
            foreach (var fieldMapping in recordMapping.FieldMappings)
            {
                if (fieldMapping.ConverterTypeName != null)
                {
                    writer.WriteLine($"private readonly {fieldMapping.ConverterTypeName} _c{fieldMapping.FieldOrder} = new();");
                }
            }
        }

        private static void BuildRegisterMethod(SourceTextWriter writer, string typeName, in TabularRecordMapping recordMapping)
        {
            writer.WriteLine("[global::System.Runtime.CompilerServices.ModuleInitializer]");
            writer.WriteLine("public static void Register()");
            writer.WriteLine("{");
            writer.Indent++;
            writer.WriteLine($"global::Addax.Formats.Tabular.TabularRegistry.Handlers[typeof({recordMapping.TypeName})] = new {typeName}();");
            writer.Indent--;
            writer.WriteLine("}");
        }

        private static void BuildReadMethod(SourceTextWriter writer, in TabularRecordMapping recordMapping, bool isAsync)
        {
            var trySkipFieldCall = isAsync ? "await reader.TrySkipFieldAsync(cancellationToken).ConfigureAwait(false)" : "reader.TrySkipField()";
            var tryReadFieldCall = isAsync ? "await reader.TryReadFieldAsync(cancellationToken).ConfigureAwait(false)" : "reader.TryReadField()";

            if (isAsync)
            {
                writer.WriteLine($"public override async global::System.Threading.Tasks.ValueTask<{recordMapping.TypeName}> ReadAsync(global::Addax.Formats.Tabular.TabularReader reader, global::System.Threading.CancellationToken cancellationToken)");
            }
            else
            {
                writer.WriteLine($"public override {recordMapping.TypeName} Read(global::Addax.Formats.Tabular.TabularReader reader)");
            }

            writer.WriteLine("{");
            writer.Indent++;
            writer.WriteLine("var n = reader.RecordsRead;");
            writer.WriteLine();

            var converterNames = BuildConverterResolution(writer, recordMapping, "reader", TabularFieldAccess.Read);
            var currentFieldOrder = -1;

            foreach (var fieldMapping in recordMapping.FieldMappings)
            {
                if ((fieldMapping.FieldAccess & TabularFieldAccess.Read) == 0)
                {
                    continue;
                }

                var fieldOrder = fieldMapping.FieldOrder;
                var missingFieldCall = $"ThrowMissingFieldException(n, {fieldOrder}, {fieldMapping.MemberNameLiteral});";
                var fieldConversionCall = $"ThrowFieldConversionException<{fieldMapping.ValueTypeName}>(n, {fieldOrder}, {fieldMapping.MemberNameLiteral});";
                var fieldsToSkip = fieldOrder - (currentFieldOrder + 1);

                if (fieldsToSkip > 0)
                {
                    BuildFieldCheck(writer, trySkipFieldCall, missingFieldCall);

                    writer.WriteLine();

                    if (fieldsToSkip > 1)
                    {
                        writer.WriteLine($"for (var i = 1; i < {fieldsToSkip}; i++)");
                        writer.WriteLine("{");
                        writer.Indent++;

                        BuildFieldCheck(writer, trySkipFieldCall, missingFieldCall);

                        writer.Indent--;
                        writer.WriteLine("}");
                        writer.WriteLine();
                    }
                }

                BuildFieldCheck(writer, tryReadFieldCall, missingFieldCall);

                writer.WriteLine();

                var valueName = (fieldMapping.ValueTypeModifier != TabularTypeModifier.None) ? $"f{fieldOrder}" : $"v{fieldOrder}";
                var tryGetCall = default(string);

                if (fieldMapping.ConverterTypeName != null)
                {
                    tryGetCall = $"reader.TryGet(_c{fieldOrder}, out var {valueName})";
                }
                else if (fieldMapping.ValueTypeCode != null)
                {
                    tryGetCall = $"reader.TryGet{fieldMapping.ValueTypeCode}(out var {valueName})";
                }
                else
                {
                    tryGetCall = $"reader.TryGet({converterNames[fieldMapping.ValueTypeKey]}, out var {valueName})";
                }

                if ((fieldMapping.ValueTypeModifier != TabularTypeModifier.None) && (fieldMapping.ValueTypeCode == "String"))
                {
                    writer.WriteLine($"reader.TryGetString(out var f{fieldOrder});");
                    writer.WriteLine();
                    writer.WriteLine($"var v{fieldOrder} = global::System.String.IsNullOrEmpty(f{fieldOrder}) ? null : f{fieldOrder};");
                }
                else if (fieldMapping.ValueTypeModifier != TabularTypeModifier.None)
                {
                    var defaultValue = (fieldMapping.ValueTypeModifier == TabularTypeModifier.Nullable) ? $"default({fieldMapping.ValueTypeName}?)" : $"default({fieldMapping.ValueTypeName})";

                    writer.WriteLine($"var v{fieldOrder} = {defaultValue};");
                    writer.WriteLine();
                    writer.WriteLine("if (!reader.CurrentField.IsEmpty)");
                    writer.WriteLine("{");
                    writer.Indent++;
                    writer.WriteLine($"if (!{tryGetCall})");
                    writer.WriteLine("{");
                    writer.Indent++;
                    writer.WriteLine(fieldConversionCall);
                    writer.Indent--;
                    writer.WriteLine("}");
                    writer.WriteLine();
                    writer.WriteLine($"v{fieldOrder} = f{fieldOrder};");
                    writer.Indent--;
                    writer.WriteLine("}");
                }
                else
                {
                    writer.WriteLine($"if (!{tryGetCall})");
                    writer.WriteLine("{");
                    writer.Indent++;
                    writer.WriteLine(fieldConversionCall);
                    writer.Indent--;
                    writer.WriteLine("}");
                }

                writer.WriteLine();
                currentFieldOrder = fieldOrder;
            }

            BuildRecordConstruction(writer, recordMapping);

            writer.WriteLine();
            writer.WriteLine("return r;");
            writer.Indent--;
            writer.WriteLine("}");
        }

        private static Dictionary<string, string> BuildConverterResolution(SourceTextWriter writer, in TabularRecordMapping recordMapping, string engineName, TabularFieldAccess fieldAccess)
        {
            var converterNames = new Dictionary<string, string>(StringComparer.Ordinal);

            foreach (var fieldMapping in recordMapping.FieldMappings)
            {
                if (((fieldMapping.FieldAccess & fieldAccess) != 0) && (fieldMapping.ConverterTypeName == null) && (fieldMapping.ValueTypeCode == null) && !converterNames.ContainsKey(fieldMapping.ValueTypeKey))
                {
                    var converterName = $"c{fieldMapping.FieldOrder}";

                    writer.WriteLine($"var {converterName} = {engineName}.ResolveConverter<{fieldMapping.ValueTypeName}>();");
                    converterNames.Add(fieldMapping.ValueTypeKey, converterName);
                }
            }

            if (converterNames.Count != 0)
            {
                writer.WriteLine();
            }

            return converterNames;
        }

        private static void BuildFieldCheck(SourceTextWriter writer, string tryFieldCall, string missingFieldCall)
        {
            writer.WriteLine($"if (!{tryFieldCall})");
            writer.WriteLine("{");
            writer.Indent++;
            writer.WriteLine(missingFieldCall);
            writer.Indent--;
            writer.WriteLine("}");
        }

        private static void BuildRecordConstruction(SourceTextWriter writer, in TabularRecordMapping recordMapping)
        {
            if (!recordMapping.ConstructorArguments.IsEmpty)
            {
                var constructorArguments = string.Join(", ", recordMapping.ConstructorArguments.Select(x => $"v{x}"));

                writer.WriteLine($"var r = new {recordMapping.TypeName}({constructorArguments});");

                return;
            }

            writer.WriteLine($"var r = new {recordMapping.TypeName}");
            writer.WriteLine("{");
            writer.Indent++;

            foreach (var fieldMapping in recordMapping.FieldMappings)
            {
                if ((fieldMapping.FieldAccess & TabularFieldAccess.Read) != 0)
                {
                    writer.WriteLine($"{fieldMapping.MemberIdentifier} = v{fieldMapping.FieldOrder},");
                }
            }

            writer.Indent--;
            writer.WriteLine("};");
        }

        private static void BuildWriteMethod(SourceTextWriter writer, in TabularRecordMapping recordMapping, bool isAsync)
        {
            if (isAsync)
            {
                writer.WriteLine($"public override async global::System.Threading.Tasks.ValueTask WriteAsync(global::Addax.Formats.Tabular.TabularWriter writer, {recordMapping.TypeName} record, global::System.Threading.CancellationToken cancellationToken)");
            }
            else
            {
                writer.WriteLine($"public override void Write(global::Addax.Formats.Tabular.TabularWriter writer, {recordMapping.TypeName} record)");
            }

            writer.WriteLine("{");
            writer.Indent++;

            var converterNames = BuildConverterResolution(writer, recordMapping, "writer", TabularFieldAccess.Write);

            for (var i = 0; i < recordMapping.FieldMappings.Count; i++)
            {
                var fieldMapping = recordMapping.FieldMappings[i];

                if ((fieldMapping.FieldAccess & TabularFieldAccess.Write) == 0)
                {
                    continue;
                }

                var fieldOrder = fieldMapping.FieldOrder;
                var writeMethodName = (fieldMapping.ValueTypeCode != null) ? $"Write{fieldMapping.ValueTypeCode}" : "Write";
                var converterArgument = default(string);

                if (fieldMapping.ConverterTypeName != null)
                {
                    converterArgument = $", _c{fieldOrder}";
                }
                else if (fieldMapping.ValueTypeCode != null)
                {
                    converterArgument = "";
                }
                else
                {
                    converterArgument = $", {converterNames[fieldMapping.ValueTypeKey]}";
                }

                if (fieldMapping.ValueTypeModifier == TabularTypeModifier.Nullable)
                {
                    writer.WriteLine($"if (record.{fieldMapping.MemberIdentifier} is {{ }} v{fieldOrder})");
                    writer.WriteLine("{");
                    writer.Indent++;
                    writer.WriteLine(GetWriterCall(writeMethodName, $"v{fieldOrder}{converterArgument}", isAsync));
                    writer.Indent--;
                    writer.WriteLine("}");
                    writer.WriteLine("else");
                    writer.WriteLine("{");
                    writer.Indent++;
                    writer.WriteLine(GetWriterCall("WriteEmpty", "", isAsync));
                    writer.Indent--;
                    writer.WriteLine("}");
                }
                else
                {
                    writer.WriteLine(GetWriterCall(writeMethodName, $"record.{fieldMapping.MemberIdentifier}{converterArgument}", isAsync));
                }

                if (i < recordMapping.FieldMappings.Count - 1)
                {
                    writer.WriteLine();
                }
            }

            writer.Indent--;
            writer.WriteLine("}");
        }

        private static string GetWriterCall(string methodName, string arguments, bool isAsync)
        {
            if (isAsync)
            {
                var asyncArguments = (arguments.Length != 0) ? $"{arguments}, cancellationToken" : "cancellationToken";

                return $"await writer.{methodName}Async({asyncArguments}).ConfigureAwait(false);";
            }

            return $"writer.{methodName}({arguments});";
        }

        private static void BuildThrowFieldConversionMethod(SourceTextWriter writer)
        {
            writer.WriteLine("[global::System.Diagnostics.CodeAnalysis.DoesNotReturn]");
            writer.WriteLine("[global::System.Diagnostics.StackTraceHidden]");
            writer.WriteLine("private static void ThrowFieldConversionException<T>(global::System.Int64 recordIndex, global::System.Int32 fieldOrder, global::System.String memberName)");
            writer.WriteLine("{");
            writer.Indent++;
            writer.WriteLine("throw new global::Addax.Formats.Tabular.TabularException($\"The field {fieldOrder} of the record {recordIndex} cannot be converted to '{typeof(T)}' for the member '{memberName}'.\");");
            writer.Indent--;
            writer.WriteLine("}");
        }

        private static void BuildThrowMissingFieldMethod(SourceTextWriter writer)
        {
            writer.WriteLine("[global::System.Diagnostics.CodeAnalysis.DoesNotReturn]");
            writer.WriteLine("[global::System.Diagnostics.StackTraceHidden]");
            writer.WriteLine("private static void ThrowMissingFieldException(global::System.Int64 recordIndex, global::System.Int32 fieldOrder, global::System.String memberName)");
            writer.WriteLine("{");
            writer.Indent++;
            writer.WriteLine("throw new global::Addax.Formats.Tabular.TabularException($\"The record {recordIndex} has no field {fieldOrder} for the member '{memberName}'.\");");
            writer.Indent--;
            writer.WriteLine("}");
        }

        private static void BuildHeaderProperty(SourceTextWriter writer)
        {
            writer.WriteLine("public override global::System.Collections.Generic.IEnumerable<global::System.String> Header");
            writer.WriteLine("{");
            writer.Indent++;
            writer.WriteLine("get");
            writer.WriteLine("{");
            writer.Indent++;
            writer.WriteLine("return s_header;");
            writer.Indent--;
            writer.WriteLine("}");
            writer.Indent--;
            writer.WriteLine("}");
        }
    }
}
